test('a slider hands every value it is dragged through live, and the one it is let go at once; the number beside it is kept inside its bounds', async () => {
  const onChange = vi.fn()
  render(<Slider label="fov" min={10} max={120} step={1} value={62} onChange={onChange} />)
  const track = screen.getByRole('slider', { name: 'fov' })
  fireEvent.change(track, { target: { value: '70' } })
  fireEvent.change(track, { target: { value: '80' } })
  expect(onChange.mock.calls).toEqual([[70, false], [80, false]])
  expect(screen.getByRole('spinbutton', { name: 'fov value' })).toHaveTextContent('80')
  fireEvent.pointerUp(track)
  expect(onChange).toHaveBeenLastCalledWith(80, true)
  expect(onChange).toHaveBeenCalledTimes(3)
  const user = userEvent.setup()
  await user.click(screen.getByRole('spinbutton', { name: 'fov value' }))
  await user.clear(screen.getByRole('textbox', { name: 'fov value' }))
  await user.type(screen.getByRole('textbox', { name: 'fov value' }), '500{Enter}')
  expect(onChange).toHaveBeenLastCalledWith(120, true)
})

test('a dial is a bearing clockwise from up: dragged to the right is 90, Shift snaps to 15, the arrows turn it a degree, and it wraps', () => {
  const onChange = vi.fn()
  const { rerender } = render(<AngleDial label="wind" value={350} onChange={onChange} />)
  const dial = screen.getByRole('slider', { name: 'wind' })
  dial.getBoundingClientRect = () => ({ left: 0, top: 0, width: 24, height: 24, right: 24, bottom: 24, x: 0, y: 0, toJSON() {} })
  fireEvent.pointerDown(dial, { clientX: 24, clientY: 12 })
  expect(onChange).toHaveBeenLastCalledWith(90, false)
  fireEvent.pointerMove(dial, { clientX: 12, clientY: 24, shiftKey: true })
  expect(onChange).toHaveBeenLastCalledWith(180, false)
  fireEvent.pointerMove(dial, { clientX: 3, clientY: 20, shiftKey: true })
  expect(onChange).toHaveBeenLastCalledWith(225, false)
  fireEvent.pointerUp(dial)
  expect(onChange).toHaveBeenLastCalledWith(225, true)
  rerender(<AngleDial label="wind" value={359} onChange={onChange} />)
  fireEvent.keyDown(dial, { key: 'ArrowRight' })
  expect(onChange).toHaveBeenLastCalledWith(0, true)
  fireEvent.keyDown(dial, { key: 'ArrowLeft', shiftKey: true })
  expect(onChange).toHaveBeenLastCalledWith(344, true)
})

test('a rule is a ramp from lo to hi, inverted when lo is above hi and a step when they are one; each part is its own field', async () => {
  // The ramp drawn over [0, 1], 60 wide and 16 high: y 15 is 0 and y 1 is 1.
  const onChange = vi.fn()
  const drawn = () => screen.getByRole('img').querySelector('polyline')!.getAttribute('points')!.split(' ').map(p => p.split(',').map(v => +(+v).toFixed(3)))
  const { rerender } = render(<RampField label="slope rule" keys={['height', 'slope']} range={[0, 1]} value={{ q: 'slope', lo: 0.3, hi: 0.6 }} onChange={onChange} />)
  expect(screen.getByRole('img', { name: 'slope rises from 0.3 to 0.6' })).toBeInTheDocument()
  expect(drawn()).toEqual([[0, 15], [18, 15], [36, 1], [60, 1]])
  rerender(<RampField label="slope rule" keys={['height', 'slope']} range={[0, 1]} value={{ q: 'slope', lo: 0.6, hi: 0.3 }} onChange={onChange} />)
  expect(screen.getByRole('img', { name: 'slope falls from 0.6 to 0.3' })).toBeInTheDocument()
  expect(drawn()).toEqual([[0, 1], [18, 1], [36, 15], [60, 15]])
  rerender(<RampField label="slope rule" keys={['height', 'slope']} range={[0, 1]} value={{ q: 'slope', lo: 0.5, hi: 0.5 }} onChange={onChange} />)
  expect(drawn()).toEqual([[0, 15], [30, 15], [30, 1], [60, 1]])
  rerender(<RampField label="slope rule" keys={['height', 'slope']} value={{ q: 'slope', lo: 0.6, hi: 0.3 }} onChange={onChange} />)
  const user = userEvent.setup()
  await user.selectOptions(screen.getByRole('combobox', { name: 'slope rule of' }), 'height')
  expect(onChange).toHaveBeenLastCalledWith({ q: 'height', lo: 0.6, hi: 0.3 }, true)
  await user.click(screen.getByRole('spinbutton', { name: 'slope rule hi' }))
  await user.clear(screen.getByRole('textbox', { name: 'slope rule hi' }))
  await user.type(screen.getByRole('textbox', { name: 'slope rule hi' }), '0.9{Enter}')
  expect(onChange).toHaveBeenLastCalledWith({ q: 'slope', lo: 0.6, hi: 0.9 }, true)
})
